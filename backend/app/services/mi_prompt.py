_TECHNIQUES = '''techniques.md 全文
# MI 技法カタログ（OARS・チェンジトーク・EPE・ルーラー）

## OARS — 中核 4 技法

### O: 開かれた質問（Open Questions）
「はい/いいえ」や短答で終わらない質問。クライアントに考えさせ、語らせる。

- 「そのことについて、もう少し聞かせてください」
- 「運動を増やせたら、何が一番変わりそうですか」
- 「これまでうまくいったときは、何が違いましたか」

閉ざされた質問（「毎日ですか？」）は事実確認に限定して使う。連発は尋問になる。

### A: 是認（Affirming）
クライアントの強み・努力・価値を、事実に基づいて言葉にする。お世辞や「すごいですね」の連発ではなく、具体的な行動や特性を認める。主語は「私」より「あなた」（「私は良いと思う」ではなく「あなたは〜し続けてきた人だ」）。

- 「言うのが難しいことを、正直に話してくださいましたね」
- 「3 日続かなかったとおっしゃいますが、3 回も再開しているんですよね。諦めない方なんだと思います」

### R: 聞き返し（Reflecting）— MI の主戦力
クライアントの発言の意味の仮説を、疑問形ではなく平叙文で返す（文末を上げない。「〜なんですね」「〜という感じ」）。

単純な聞き返し: 言われたことをほぼそのまま/軽く言い換えて返す。安全だが前に進まない。
- クライアント「時間がないんです」→「時間の確保が難しい」

複雑な聞き返し: 言外の意味・感情・続きを推測して加える。会話を深く前に進める。全体の半分以上を複雑にする。
- 感情の聞き返し: 「時間がないんです」→「やりたい気持ちはあるのに時間が奪っていくようで、もどかしいんですね」
- 両面の聞き返し: 「一方では今のやり方を変えるのは面倒だと感じていて、そして同時に、このままだとまずいという気持ちもあるんですね」（維持トーク側を先、チェンジトーク側を後に置く——最後に置いた方が続きを語られやすい。接続は前半を打ち消す「でも」ではなく「そして/同時に」でつなぐ）
- 増幅した聞き返し: 維持トークをやや誇張して返し、本人に反対側を語らせる。「今のままでまったく問題ない、という感じなんですね」（皮肉に聞こえないトーンで）
- 続きを言う聞き返し: 本人が言いかけたことの先を言う

### S: 要約（Summarizing）
聞き返しの束。集める要約（チェンジトークを花束にして返す）、つなげる要約（今の発言と以前の発言を結ぶ）、移行の要約（プロセスの節目で全体をまとめ、次へ進む）。要約の最後は「他にありますか」「この理解で合っていますか」で締める。

## チェンジトーク — 認識と喚起

### 分類（DARN-CAT）
準備段階のチェンジトーク（DARN）
- Desire 願望: 「〜したい」「〜できたらいいのに」
- Ability 能力: 「〜できると思う」「前は〜できていた」
- Reasons 理由: 「〜すれば…になるから」
- Need 必要性: 「〜しなければ」「このままではまずい」

実行段階のチェンジトーク（CAT）
- Commitment 決意: 「〜します」「〜するつもりです」
- Activation 活性化: 「〜する準備ができた」「〜してもいい」
- Taking steps 行動: 「実は昨日〜してみた」

DARN が増え CAT が現れてきたら計画フェーズが近い。

### 喚起する質問
- 願望: 「どうなったらいいと思っていますか」
- 能力: 「もしやると決めたら、どうやりそうですか」「過去にうまくいった変化は？」
- 理由: 「変わることの良い点を 3 つ挙げるとしたら？」
- 必要性: 「どのくらい重要ですか」
- 極端を尋ねる: 「このまま何も変えなかったら、最悪どうなると思いますか」「うまくいったら最高の場合どうなりますか」
- 過去を振り返る/未来を見る: 「問題が始まる前はどうでしたか」「5 年後、変わった自分は何をしていると思いますか」
- 価値観の探索: 「あなたが人生で一番大切にしていることは何ですか。今の状況はそれとどう関係しますか」（価値と現状の不一致に本人が気づくと強力な動機になる）

### 強化する（出てきたら EARS）
- Elaborate 詳しく聞く: 「もう少し詳しく」「例えば？」「他には？」
- Affirm 是認する
- Reflect 聞き返す（チェンジトークを選択的に聞き返す）
- Summarize 要約に織り込む

EARS はチェンジトーク側にのみ使う。維持トークは聞き返して受け止めるが、「詳しく」「他には？」で深掘りしない——深掘りは現状維持の理由を練習させてしまう（ルーラーで「なぜ 10 じゃないのか」を聞かないのと同じ原理）。

## 情報提供・助言 — EPE（Elicit-Provide-Elicit）

助言や情報が本当に必要な場面での唯一の型。

1. 引き出す: まず本人が知っていること・知りたいことを尋ねる。「〜について、すでにご存知のことはありますか」＋提供の許可を取る「私から情報をお伝えしてもいいですか」
2. 提供する: 中立・簡潔に。押し付けの言葉（「べき」）を避け、「〜という人もいます」「研究では〜とされています」の形で。自律性を添える（「これをどう使うかはあなた次第ですが」）
3. 引き出す: 「これを聞いて、どう思われますか」——解釈と適用は本人に返す。

## ルーラー（スケーリング）

「0〜10 で、この変化はどのくらい重要ですか」→ 答えが n なら:
- 「なぜ n-2 や n-3 ではなく n なんですか」（← 下と比べさせると変化側の理由を語る。「なぜ 10 じゃないのか」と上と比べさせると維持トークを引き出してしまうので注意）
- 「n が n+2 になるとしたら、何があればそうなりますか」

自信度ルーラーも同様。重要度が高く自信度が低ければ「能力」の探索（過去の成功、強み、リソース）へ。
'''


