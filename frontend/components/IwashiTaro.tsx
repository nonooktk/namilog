import Image from "next/image";

/** 画像サイズ。sm=48px 角（通常カード内）、md=64px 角（ホーム最上部など強調箇所）。§11.5 */
export type IwashiTaroSize = "sm" | "md";
/** 吹き出し背景。secondary=Secondary Light（既定）、sub=サブ背景（重なりで視認性が落ちる場合）。§11.5 */
export type IwashiTaroVariant = "secondary" | "sub";

/**
 * イワシ太郎の吹き出し。
 * @param message 「キュン！（…）」形式の全文（デザイン仕様 §11.3 の確定文言をそのまま渡す）。
 */
export function IwashiTaro({
  message,
  size = "sm",
  variant = "secondary",
}: {
  message: string;
  size?: IwashiTaroSize;
  variant?: IwashiTaroVariant;
}) {
  const px = size === "md" ? 64 : 48;
  return (
    <div
      className={`iwashi-taro${variant === "sub" ? " iwashi-taro--sub" : ""}`}
    >
      <div
        className="iwashi-taro__avatar"
        style={{ width: px, height: px }}
        aria-hidden="true"
      >
        {/* 装飾画像: alt="" + aria-hidden で読み上げ対象外（§11.5）。 */}
        <Image
          src="/iwashi-taro.png"
          alt=""
          aria-hidden="true"
          fill
          sizes="64px"
          style={{ objectFit: "contain" }}
        />
      </div>
      {/* 吹き出し本文は通常テキスト（読み上げ可能）。フォーカスは持たせない。 */}
      <p className="iwashi-taro__bubble">{message}</p>
    </div>
  );
}

